// Generate dates for current 7 days
export function getWeekDates(baseDate: Date = new Date()): { dateStr: string; dayName: string; dayNumber: number; fullDate: Date }[] {
  const days: { dateStr: string; dayName: string; dayNumber: number; fullDate: Date }[] = [];
  const dayOfWeek = baseDate.getDay(); // 0 = Sun, 1 = Mon...
  const distanceToMonday = (dayOfWeek + 6) % 7;
  
  const monday = new Date(baseDate);
  monday.setDate(baseDate.getDate() - distanceToMonday);

  const dayNames = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];

  for (let i = 0; i < 7; i++) {
    const d = new Date(monday);
    d.setDate(monday.getDate() + i);
    const yyyy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    
    days.push({
      dateStr: `${yyyy}-${mm}-${dd}`,
      dayName: dayNames[i],
      dayNumber: d.getDate(),
      fullDate: d,
    });
  }

  return days;
}

export function generateInitialShifts(employees: Employee[], weekDates: { dateStr: string; dayName: string }[]): Shift[] {
  const shifts: Shift[] = [];
  let shiftCount = 1;

  const shiftTemplates = [
    { start: '10:00', end: '16:00', label: 'Lunch Shift' },
    { start: '16:00', end: '23:30', label: 'Dinner Rush' },
    { start: '08:00', end: '15:00', label: 'Morning Prep / Open' },
    { start: '17:00', end: '01:00', label: 'Late Night Bar & Clean' },
    { start: '11:00', end: '20:00', label: 'Mid-Day Swing' },
  ];

  // Assign realistic restaurant shifts across the 7-day span
  weekDates.forEach((wd, dayIdx) => {
    // Weekends (Fri, Sat, Sun) have higher staffing
    const isWeekend = dayIdx >= 4;
    const activeStaffForDay = isWeekend ? employees.slice(0, 11) : employees.slice(0, 8);

    activeStaffForDay.forEach((emp) => {
      // Pick template based on role
      let template = shiftTemplates[1]; // default dinner
      if (emp.role === 'Prep Cook' || emp.role === 'Head Chef') {
        template = shiftTemplates[2];
      } else if (emp.role.includes('Bartender')) {
        template = isWeekend ? shiftTemplates[3] : shiftTemplates[1];
      } else if (emp.role === 'Host / Hostess' || emp.role === 'Cashier') {
        template = dayIdx % 2 === 0 ? shiftTemplates[0] : shiftTemplates[1];
      } else {
        template = (dayIdx + parseInt(emp.id.replace(/\D/g, ''))) % 2 === 0 ? shiftTemplates[0] : shiftTemplates[1];
      }

      shifts.push({
        id: `shift-${shiftCount++}`,
        employeeId: emp.id,
        employeeName: emp.name,
        department: emp.department,
        role: emp.role,
        date: wd.dateStr,
        startTime: template.start,
        endTime: template.end,
        breakMinutes: 30,
        hourlyWage: emp.hourlyWage,
        status: 'published',
        color: emp.color,
        notes: isWeekend ? 'High volume service expectation' : 'Standard station rotation',
        organizationId: emp.organizationId || 'org-shiftsky-global',
        hierarchyPath: emp.hierarchyPath || 'ShiftForce Global > North America > Pacific Coast > Bay Area District > SF Flagship Bistro #104',
        locationId: emp.locationId || 'loc-sf-flagship-104',
        districtId: emp.districtId || 'dist-bay-area-01',
        regionId: emp.regionId || 'reg-pacific-coast-01',
      });
    });
  });

  return shifts;
}

